#!/usr/bin/env bash
# Online demo (ADR 0020): writes /opt/astax/demo.env with fresh random secrets.
# Run once on the server; it never overwrites an existing file and never
# prints a secret (rule 12). The Resend key is added later by set-resend-key.sh.
set -euo pipefail

DOMAIN="${1:?usage: make-env.sh <domain>, for example astaxapp.com}"
TARGET=/opt/astax/demo.env

if [ -e "$TARGET" ]; then
  echo "$TARGET exists already: nothing changed."
  exit 0
fi

hex() { openssl rand -hex 32; }
pg_super=$(hex) db_owner=$(hex) db_app=$(hex) kc_db=$(hex) redis=$(hex)
kc_admin=$(hex) kc_api=$(hex) s3_key=$(openssl rand -hex 16) s3_secret=$(hex)
dev_users=$(openssl rand -base64 18 | tr -d '/+=' | cut -c1-20)

umask 077
cat >"$TARGET" <<EOF
# AstAx online demo (ADR 0020). Synthetic data and fake providers only.
# Generated by infra/demo/make-env.sh: never copy it into the repository.
DOMAIN=$DOMAIN
IMAGE_TAG=none

# Not production by construction: the release gate refuses this (rule 13).
NODE_ENV=development
DEV_TOOLS=true
DEMO_NOTICE=true
LOG_LEVEL=info

WEB_URL=https://demo.$DOMAIN
ADMIN_URL=https://bo.$DOMAIN
API_PUBLIC_URL=https://api.$DOMAIN
API_URL=http://api:4000
API_HOST=0.0.0.0
API_PORT=4000
API_TRUST_PROXY=uniquelocal
WEB_TRUSTED_PROXY=true

POSTGRES_SUPERUSER_PASSWORD=$pg_super
ASTAX_DB_OWNER_PASSWORD=$db_owner
ASTAX_DB_APP_PASSWORD=$db_app
KEYCLOAK_DB_PASSWORD=$kc_db
DATABASE_OWNER_URL=postgresql://astax_owner:$db_owner@postgres:5432/astax
DATABASE_URL=postgresql://astax_app:$db_app@postgres:5432/astax

REDIS_PASSWORD=$redis
REDIS_URL=redis://:$redis@redis:6379

KEYCLOAK_URL=https://accesso.$DOMAIN
KEYCLOAK_ADMIN_URL=http://keycloak:8080
KEYCLOAK_REALM=astax
KEYCLOAK_ADMIN_USER=admin
KEYCLOAK_ADMIN_PASSWORD=$kc_admin
KEYCLOAK_API_ADMIN_SECRET=$kc_api
DEV_USERS_PASSWORD=$dev_users

TEMPORAL_ADDRESS=temporal:7233
TEMPORAL_NAMESPACE=astax

S3_ENDPOINT=http://storage:8333
S3_ACCESS_KEY=$s3_key
S3_SECRET_KEY=$s3_secret
S3_REGION=eu-south-1
S3_BUCKET=astax-documents

MAILPIT_URL=http://mailpit:8025
WORKER_HEALTH_HOST=0.0.0.0

SEALED_BIDS_MASTER_KEY=$(hex)
OFFER_OWNER_MASTER_KEY=$(hex)
FIELD_ENCRYPTION_KEY=$(hex)
BLIND_INDEX_KEY=$(hex)

# Fake providers (rule 9), real email with Resend (answer 5A).
EMAIL_PROVIDER=fake
EMAIL_FROM=noreply@$DOMAIN
SMS_PROVIDER=fake
SMS_ORIGINATOR=AstAx
PUSH_PROVIDER=fake
KMS_PROVIDER=fake
AI_PROVIDER=fake
PLATE_PROVIDER=fake
SDI_PROVIDER=fake
STORAGE_PROVIDER=fake
SIGNATURE_PROVIDER=fake
PAYMENTS_PROVIDER=fake
RUI_PROVIDER=fake
EOF
echo "$TARGET written (permissions 600). Secrets were not printed."
